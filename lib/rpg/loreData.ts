// Section 11 of claude/before-variety-ideas.md: the built-in canon lore
// library. About 200 entries of world lore (history, clans, villages, groups,
// the tailed beasts, objects, secrets), for the narrator only. Each says who
// knows it, from and until when it is true, and, for some, what most people
// believe instead. Kan learns an entry only when he is told it, reads it or
// sees it; the Journal's "What you know" shows only those.
//
// Sources: the manga first, then the databooks, the novels (Itachi Shinden,
// the Hiden) and anime-only lore. Nothing from the Boruto era.
//
// `known` and `belief.heldBy` take group keys (LORE_GROUPS) or cast names.
// `from` / `until` are milestone ids: true once `from` has happened, no longer
// once `until` has. `widens` lets more people know (or believe) it as the
// story goes on. `kan` is what Kan knows at the start: the truth ('knows') or
// what most believe ('belief'); left out, he doesn't know it.

export type LoreTopic = 'history' | 'clan' | 'village' | 'group' | 'beast' | 'object' | 'secret' | 'person';

export type CanonLore = {
  id: string;
  title: string;
  topic: LoreTopic;
  /** Words that bring it up (matched as whole words, any case). */
  keywords: string[];
  /** The people it is about (cast names): it may come up when they are in the scene. */
  people?: string[];
  /** The truth, for the narrator. */
  text: string;
  /** How the Journal words it, when the narrator's text would not read well there. */
  journal?: string;
  /** Who knows the truth. */
  known: string[];
  /** What Kan knows at the start. */
  kan?: 'knows' | 'belief';
  from?: string;
  until?: string;
  /** What most people believe instead of the truth. */
  belief?: { text: string; journal?: string; heldBy: string[] };
  /** More people know (or believe) it from a milestone on. */
  widens?: { at: string; known?: string[]; held?: string[] }[];
  /** Higher comes first when several match (default 1). */
  priority?: number;
};

